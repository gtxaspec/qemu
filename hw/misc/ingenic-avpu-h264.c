/*
 * Ingenic AVPU: H.264 slice data
 *
 * libimp writes the SPS, the PPS and each slice header itself, and the AVPU
 * writes only what follows the header, with its emulation prevention bytes.
 * A CAVLC slice header need not end on a byte, so libimp writes its first
 * bytes and hands the AVPU the bits after them, which it writes before the
 * slice data; a CABAC one ends aligned.
 *
 * I pictures follow the EL150 as measured on a T31. Its quantizer leaves a
 * third of a step of dead zone. A 4x4 or 8x8 block's intra mode has the
 * least SATD, plus 6 lambda off the most probable mode; 16x16 the least
 * SAD; chroma the least SATD, plus 4 lambda off DC. The macroblock type has
 * the least luma SSD + lambda^2 R, where R is the floor of the header's
 * CABAC cost at the coder's live context states, in 1/64 bit steps with a
 * remaining-mode bit at 1, plus a residual cost that ignores the states.
 * Intra 16x16 codes its AC blocks whenever any of its luma has a level.
 * lambda is entry word 0x27's table (IngenicAvpuPic.lambda).
 *
 * P pictures are a stand-in: a macroblock is skipped, coded against the
 * last picture without motion, or intra, by luma and chroma SSD +
 * lambda^2 R. libimp's P slices refer to the picture before, alone, which
 * is kept deblocked as the decoder has it.
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 */

