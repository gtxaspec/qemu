/* -log2 p of the MPS and of the LPS at each state, in 1/64 bit */
static uint16_t bitcost[64][2];

static void h264_tables_init(void)
{
    static gsize done;

    if (!g_once_init_enter(&done)) {
        return;
    }
    for (int st = 0; st < 64; st++) {
        double lps = 0.5 * pow(0.01875 / 0.5, st / 63.0);

        bitcost[st][0] = lround(-log2(1 - lps) * 64);
        bitcost[st][1] = lround(-log2(lps) * 64);
    }
    g_once_init_leave(&done, 1);
}

/* The quantizer's round(MF * 16 / w) and LevelScale, raster: intra, inter */
typedef struct H264Quant {
    uint32_t q4[2][6][16], q8[2][6][64];
    uint32_t dq4[2][6][16], dq8[2][6][64];
} H264Quant;

static int class4(int x, int y)
{
    return !(x & 1) && !(y & 1) ? 0 : (x & 1) && (y & 1) ? 1 : 2;
}

static int class8(int x, int y)
{
    if (x % 4 == 0 && y % 4 == 0) {
        return 0;
    }
    if (x % 2 && y % 2) {
        return 1;
    }
    if (x % 4 == 2 && y % 4 == 2) {
        return 2;
    }
    if ((x % 4 == 0 && y % 2) || (x % 2 && y % 4 == 0)) {
        return 3;
    }
    if ((x % 4 == 0 && y % 4 == 2) || (x % 4 == 2 && y % 4 == 0)) {
        return 4;
    }
    return 5;
}

static void quant_setup(H264Quant *q, bool lists, const uint8_t *const *scale8)
{
    for (int t = 0; t < 2; t++) {
        for (int m = 0; m < 6; m++) {
            for (int k = 0; k < 16; k++) {
                int i = zz4[k], c = class4(i & 3, i >> 2);
                int w = lists ? default4[t][k] : 16;

                q->q4[t][m][i] = ((mf4[m][c] << 4) + w / 2) / w;
                q->dq4[t][m][i] = w * v4[m][c];
            }
            for (int k = 0; k < 64; k++) {
                int i = zz8[k], c = class8(i & 7, i >> 3);
                int w = scale8[t] ? scale8[t][k] : lists ? default8[t][k] : 16;

                q->q8[t][m][i] = ((mf8[m][c] << 4) + w / 2) / w;
                q->dq8[t][m][i] = w * v8[m][c];
            }
        }
    }
}

typedef struct BitWriter {
    GByteArray *out;
    uint32_t acc;
    int n;
} BitWriter;

static void put_bits(BitWriter *b, uint32_t v, int n)
{
    while (n--) {
        b->acc = b->acc << 1 | (v >> n & 1);
        if (++b->n == 8) {
            uint8_t byte = b->acc;

            g_byte_array_append(b->out, &byte, 1);
            b->acc = b->n = 0;
        }
    }
}

static void put_ue(BitWriter *b, uint32_t v)
{
    int len = 32 - clz32(v + 1);

    put_bits(b, 0, len - 1);
    put_bits(b, v + 1, len);
}

static void put_se(BitWriter *b, int v)
{
    put_ue(b, v > 0 ? 2 * v - 1 : -2 * v);
}

/*
 * CABAC, as the HM reference encoder writes it; without a GByteArray it
 * only prices the bins at their live states
 */
typedef struct Cabac {
    uint32_t low, range;
    int bits_left;
    int buffered;               /* bytes held back for a carry */
    uint32_t buffered_byte;
    uint32_t bits, nbits;       /* the bit writer's partial byte */
    uint8_t state[CTXS];        /* pStateIdx << 1 | valMPS */
    uint32_t bins;
    uint32_t cost;              /* in 1/64 bit */
    GByteArray *rbsp;
} Cabac;

static void cabac_put_byte(Cabac *c, uint8_t b)
{
    g_byte_array_append(c->rbsp, &b, 1);
}

static void cabac_put_bits(Cabac *c, uint32_t v, int n)
{
    while (n--) {
        c->bits = c->bits << 1 | (v >> n & 1);
        if (++c->nbits == 8) {
            cabac_put_byte(c, c->bits);
            c->bits = c->nbits = 0;
        }
    }
}

static void cabac_out(Cabac *c)
{
    uint32_t lead = c->low >> (24 - c->bits_left);

    c->bits_left += 8;
    c->low &= 0xffffffffu >> c->bits_left;
    if (lead == 0xff) {
        c->buffered++;
    } else if (c->buffered) {
        uint32_t carry = lead >> 8;

        cabac_put_byte(c, c->buffered_byte + carry);
        c->buffered_byte = lead & 0xff;
        while (c->buffered > 1) {
            cabac_put_byte(c, 0xff + carry);
            c->buffered--;
        }
    } else {
        c->buffered = 1;
        c->buffered_byte = lead;
    }
}

static void cabac_init(Cabac *c, int table, int qp, GByteArray *rbsp)
{
    memset(c, 0, sizeof(*c));
    c->range = 510;
    c->bits_left = 23;
    c->buffered_byte = 0xff;
    c->rbsp = rbsp;
    for (int i = 0; i < CTXS; i++) {
        int pre = ((ctx_init[table][i][0] * qp) >> 4) + ctx_init[table][i][1];

        pre = MIN(MAX(pre, 1), 126);
        c->state[i] = pre <= 63 ? (63 - pre) << 1 : (pre - 64) << 1 | 1;
    }
}

/* An estimator starting from @c's states */
static void cabac_fork(Cabac *est, const Cabac *c)
{
    memcpy(est->state, c->state, sizeof(est->state));
    est->rbsp = NULL;
    est->cost = 0;
}

static void cabac_update(uint8_t *s, int bin)
{
    if (bin == (*s & 1)) {
        if ((*s >> 1) < 62) {
            *s += 2;
        }
    } else {
        *s = (*s >> 1) ? lps_next[*s >> 1] << 1 | (*s & 1) : *s ^ 1;
    }
}

static void cabac_bin(Cabac *c, int ctx, int bin)
{
    uint8_t *s = &c->state[ctx];
    bool lps_bin = bin != (*s & 1);
    uint32_t lps;

    if (!c->rbsp) {
        c->cost += bitcost[*s >> 1][lps_bin];
        cabac_update(s, bin);
        return;
    }
    lps = lps_table[*s >> 1][(c->range >> 6) & 3];
    cabac_update(s, bin);
    c->bins++;
    c->range -= lps;
    if (lps_bin) {
        int n = 0;

        while ((lps << n) < 256) {
            n++;
        }
        c->low = (c->low + c->range) << n;
        c->range = lps << n;
        c->bits_left -= n;
    } else {
        if (c->range >= 256) {
            return;
        }
        c->low <<= 1;
        c->range <<= 1;
        c->bits_left--;
    }
    if (c->bits_left < 12) {
        cabac_out(c);
    }
}

/* The estimate prices each rem_intra_pred_mode bin at one bit */
static void cabac_rem(Cabac *c, int bin)
{
    if (!c->rbsp) {
        c->cost += 64;
        cabac_update(&c->state[CTX_REM_MODE], bin);
        return;
    }
    cabac_bin(c, CTX_REM_MODE, bin);
}

static void cabac_bypass(Cabac *c, uint32_t bins, int n)
{
    if (!c->rbsp) {
        return;
    }
    c->bins += n;
    while (n--) {
        c->low <<= 1;
        if (bins >> n & 1) {
            c->low += c->range;
        }
        if (--c->bits_left < 12) {
            cabac_out(c);
        }
    }
}

static void cabac_terminate(Cabac *c, int bin)
{
    if (!c->rbsp) {
        return;
    }
    c->bins++;
    c->range -= 2;
    if (bin) {
        c->low += c->range;
        c->low <<= 7;
        c->range = 2 << 7;
        c->bits_left -= 7;
    } else if (c->range >= 256) {
        return;
    } else {
        c->low <<= 1;
        c->range <<= 1;
        c->bits_left--;
    }
    if (c->bits_left < 12) {
        cabac_out(c);
    }
}

/* Flush, then rbsp_slice_trailing_bits */
static void cabac_finish(Cabac *c)
{
    if (c->low >> (32 - c->bits_left)) {
        cabac_put_byte(c, c->buffered_byte + 1);
        while (c->buffered > 1) {
            cabac_put_byte(c, 0);
            c->buffered--;
        }
        c->low -= 1 << (32 - c->bits_left);
    } else {
        if (c->buffered) {
            cabac_put_byte(c, c->buffered_byte);
        }
        while (c->buffered > 1) {
            cabac_put_byte(c, 0xff);
            c->buffered--;
        }
    }
    cabac_put_bits(c, c->low >> 8, 24 - c->bits_left);
    cabac_put_bits(c, 1, 1);
    if (c->nbits) {
        cabac_put_bits(c, 0, 8 - c->nbits);
    }
}

