/*
 * Ingenic MIPI D-PHY (T23, T30, T31, T32, T33, T40 and T41)
 *
 * Byte registers at word stride, held in reset while the CSI host's
 * DPHY_RSTZ is low: the window then reads 0 and keeps no write. Letting it
 * go brings every register up at its power-on value, and holding it again
 * loses what was written; PHY_SHUTDOWNZ and CSI2_RESETN do neither. One
 * KiB of registers repeats across the 4 KiB window; the T41's sit in its
 * second KiB alone, with more at 0x900. Values and the bits a write keeps
 * are as a T23N, T30X, T31X, T32LQ (the T33 alike, unmeasured), T40XP and
 * T41NQ read them, released at their U-Boot prompts; the byte at 0x74 of
 * each lane's 0x80 reads 3 and keeps no write, with no sensor running.
 * With one streaming, a T31X's data lanes read 0x2b and 0x22 at 0x1d0 and
 * 0x1d4, 0x80 and 0x22 at 0x250 and 0x254, status the model leaves at 0:
 * it has no lanes to sense.
 *
 * Copyright (C) 2026 Alfonso Gamboa <gtxent@gmail.com>
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 */

