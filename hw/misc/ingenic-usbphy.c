/*
 * Ingenic USB PHY (Innosilicon USB 2.0), the T20 to the T41 and the A1
 *
 * Byte registers at word stride, 1 KiB per PHY at 0x10060000. One PHY
 * answers at every 1 KiB of the 4 KiB window; the A1's three take the first
 * three and its fourth reads 0; the T10 has none, its window reading 0 and
 * keeping no write. Each
 * register's value out of reset and the bits a write keeps are as the parts
 * read them, with the OTG clock open and nothing driving the bus: a T20X
 * (its own layout), a T31X (the T21N and T30X read alike), a T23N (the
 * T23DL and T32LQ alike), a T40XP, a T41NQ and an A1N. 0x140 and 0x14c are
 * status; from the T40 on 0x164 to 0x170 are too, a calibration result
 * that differs from part to part and between the A1's PHYs. Nothing moves
 * them here: the model has no line to sense. No CPM signal resets these
 * registers: a T23N, T31X and T41NQ keep them through USBPCR.POR (which the
 * T21 manual says resets the PHY's test registers), USBRDT.UTMI_RST, SRBC's
 * USB soft reset, suspend and the OTG clock gate.
 *
 * Copyright (C) 2026 Alfonso Gamboa <gtxent@gmail.com>
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 */

