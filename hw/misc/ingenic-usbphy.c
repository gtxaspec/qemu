static void ingenic_usbphy_class_init(ObjectClass *klass, const void *data)
{
    DeviceClass *dc = DEVICE_CLASS(klass);
    ResettableClass *rc = RESETTABLE_CLASS(klass);

    dc->realize = ingenic_usbphy_realize;
    rc->phases.hold = ingenic_usbphy_reset_hold;
    dc->vmsd = &vmstate_ingenic_usbphy;
    device_class_set_props(dc, ingenic_usbphy_properties);
}

