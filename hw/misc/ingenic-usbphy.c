typedef struct {
    const char *model;
    uint32_t phys;
    const uint8_t *wmask;
    const uint8_t *reset;
} IngenicUsbPhyModel;

static const IngenicUsbPhyModel models[] = {
    { "t10", 0 },
    { "t20", 1, wmask_t20, reset_t20 },
    { "t31", 1, wmask_t31, reset_t31 },
    { "t23", 1, wmask_t23, reset_t23 },
    { "t40", 1, wmask_t23, reset_t40 },
    { "t41", 1, wmask_t41, reset_t41 },
    { "a1", 3, wmask_t23, reset_a1 },
};

static unsigned ingenic_usbphy_phy(IngenicUsbPhyState *s, hwaddr offset)
{
    return s->phys == 1 ? 0 : offset / PHY_SIZE;
}

static uint64_t ingenic_usbphy_read(void *opaque, hwaddr offset,
                                    unsigned size)
{
    IngenicUsbPhyState *s = INGENIC_USBPHY(opaque);
    unsigned phy = ingenic_usbphy_phy(s, offset);

    if (phy >= s->phys || offset & 3) {
        return 0;
    }
    return s->regs[phy][(offset % PHY_SIZE) / 4];
}

static void ingenic_usbphy_write(void *opaque, hwaddr offset,
                                 uint64_t value, unsigned size)
{
    IngenicUsbPhyState *s = INGENIC_USBPHY(opaque);
    unsigned phy = ingenic_usbphy_phy(s, offset);
    unsigned i = (offset % PHY_SIZE) / 4;

    if (phy >= s->phys || offset & 3) {
        return;
    }
    s->regs[phy][i] = (s->regs[phy][i] & ~s->wmask[i]) | (value & s->wmask[i]);
}

static const MemoryRegionOps ingenic_usbphy_ops = {
    .read = ingenic_usbphy_read,
    .write = ingenic_usbphy_write,
    .endianness = DEVICE_LITTLE_ENDIAN,
    .valid = { .min_access_size = 1, .max_access_size = 4 },
    .impl = { .min_access_size = 1, .max_access_size = 4 },
};

static void ingenic_usbphy_reset_hold(Object *obj, ResetType type)
{
    IngenicUsbPhyState *s = INGENIC_USBPHY(obj);

    for (unsigned i = 0; i < s->phys; i++) {
        memcpy(s->regs[i], s->reset, INGENIC_USBPHY_REGS);
    }
}

static void ingenic_usbphy_init(Object *obj)
{
    IngenicUsbPhyState *s = INGENIC_USBPHY(obj);

    memory_region_init_io(&s->iomem, obj, &ingenic_usbphy_ops, s,
                          TYPE_INGENIC_USBPHY, 4 * KiB);
    sysbus_init_mmio(SYS_BUS_DEVICE(obj), &s->iomem);
}

static void ingenic_usbphy_realize(DeviceState *dev, Error **errp)
{
    IngenicUsbPhyState *s = INGENIC_USBPHY(dev);

    for (int i = 0; i < ARRAY_SIZE(models); i++) {
        if (s->model && !strcmp(s->model, models[i].model)) {
            s->phys = models[i].phys;
            s->wmask = models[i].wmask;
            s->reset = models[i].reset;
            return;
        }
    }
    error_setg(errp, "ingenic-usbphy: unknown model '%s'",
               s->model ? s->model : "");
}

